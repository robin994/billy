export function billyLanguage(source) {
  const raw =
    typeof source === 'string'
      ? source
      : source?.language ||
        source?.locale?.language ||
        globalThis.navigator?.language ||
        'en'
  const normalized = String(raw || 'en')
    .toLowerCase()
    .replace('_', '-')
    .split('-', 1)[0]
  return Object.prototype.hasOwnProperty.call(BILLY_TRANSLATIONS, normalized)
    ? normalized
    : 'en'
}

export function billyLocale(source) {
  const language = billyLanguage(source)
  return (
    {
      en: 'en-US',
      it: 'it-IT',
      es: 'es-ES',
      fr: 'fr-FR',
      de: 'de-DE',
      pt: 'pt-PT',
    }[language] || 'en-US'
  )
}

export function billyT(source, key, vars = {}) {
  const language = billyLanguage(source)
  let text =
    BILLY_TRANSLATIONS[language]?.[key] ?? BILLY_TRANSLATIONS.en?.[key] ?? key
  for (const [name, value] of Object.entries(vars || {})) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function billyCategoryLabel(source, category) {
  if (!category) return ''
  const id = typeof category === 'string' ? category : String(category.id || '')
  const fallback =
    typeof category === 'string' ? category : String(category.name || id)
  if (fallback === 'Bolletta rimossa') return billyT(source, 'category.removed')
  const key = `category.${id}`
  const translated = billyT(source, key)
  if (translated === key) return fallback
  const storedName = fallback.trim()
  if (storedName && storedName !== id) {
    const isDefaultName = Object.values(BILLY_TRANSLATIONS).some(
      (labels) => labels[key] === storedName,
    )
    if (!isDefaultName) return storedName
  }
  return translated
}
